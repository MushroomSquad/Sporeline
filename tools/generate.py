def wd(path: str) -> str:
    return f"{inp('workdir')}/{path}"


def base_inputs(stages: list[str]) -> dict:
    inputs = {
        "job_prefix": {"default": "", "description": "Job name prefix: several components in one pipeline (monorepo, version matrix)"},
        "workdir": {"default": ".", "description": "Project directory relative to the repository root"},
        "strict": {"type": "boolean", "default": True, "description": "false — a soft step failing (tests, linters, analysis) doesn't block the pipeline"},
        "runner_tag": {"default": "$RUNNER_TAG", "description": "Runner tag"},
        "registry_host": {"default": "$NEXUS_HOST", "description": "Registry the job images are pulled from"},
        "push_registry_host": {"default": "", "description": "Registry to publish images to (empty — REGISTRY_INT_HOST or registry_host)"},
        "images_folder": {"default": "$DST_STORAGE_FOLDER", "description": "Platform image folder in the registry"},
        "image_flavor": {"default": "ubi9", "options": FLAVORS, "description": "Base OS of the images"},
        "core_version": {"default": VERSION, "description": "Core (ci) version — the wrapper images' tag"},
        "ci_bin": {"default": "ci", "description": "Core command (for the templates repo's own e2e — path to core/bin/ci)"},
        "tools_image": {"default": "$HCI_TOOLS_IMAGE_AUTO", "description": "Image for image and analysis steps"},
    }
    for s in stages:
        inputs[f"stage_{s}"] = {"default": {"build": "build", "test": "test", "publish": "deploy"}[s], "description": f"Stage for the {s} steps"}
