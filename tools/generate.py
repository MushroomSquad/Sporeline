def step_inputs(steps: list[str]) -> dict:
    out = {}
    for s in steps:
        if s in OPTIONAL_STEPS:
            name, default, desc = OPTIONAL_STEPS[s]
            out[name] = {"type": "boolean", "default": default, "description": desc}
    if "appscreener" in steps:
        out["appscreener_runner_tag"] = {"default": "$RUNNER_TAG", "description": "Runner tag for appScreener"}
    if "kcs" in steps:
        out["kcs_runner_tag"] = {"default": "hyperion-kcs", "description": "Runner tag for KCS"}
    return out


def image_inputs() -> dict:
    return {
        "image_build_mode": {"default": "auto", "options": ["auto", "base", "dockerfile", "s2i", "cekit"], "description": "Image build mode"},
        "image_platforms": {"default": "linux/amd64", "description": "Comma-separated image platforms (multi-arch)"},
        "runtime_image": {"default": "", "description": "Base application image (empty — taken from meta.yaml for runtime_version)"},
    }


def job_name(step: str) -> str:
    return f"{inp('job_prefix')}{step}"


def need(step: str, artifacts: bool = True, optional: bool = False) -> dict:
    n = {"job": job_name(step), "artifacts": artifacts}
    if optional:
        n["optional"] = True
    return n


def rules(enabled: bool = True, image_only: bool = False, library_only: bool = False, tag_only: bool = False) -> list:
    """Minimal default rules. Any complex logic is an override in the project's YAML."""
    cond = []
    if tag_only:
        cond.append("$CI_COMMIT_TAG")
    if enabled:
        cond.append('$HCI_JOB_ENABLED == "true"')
    if image_only:
        cond.append('$HCI_SERVICE_TYPE == "image"')
    if library_only:
        cond.append('$HCI_SERVICE_TYPE == "library"')
    return [{"if": " && ".join(cond)}] if cond else [{"when": "on_success"}]


